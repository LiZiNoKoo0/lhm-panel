"""Extract an 8x16 dot-matrix font from a Windows font, once, and commit the table.

Why this exists: the ST7735 preview has to show the same glyph shapes the
firmware will blit, so the shapes cannot come from Tk (a TrueType rasteriser
with antialiasing). We pull crisp 1-bit bitmaps out of a fixed-pitch system font
with GDI, dump them as bytes, and also emit a C header so the firmware uses the
very same table -- preview and panel then agree by construction.

    python tools/font8x16_gen.py            # rewrite pcmon/font8x16.py
    python tools/font8x16_gen.py --art      # also print the bitmaps as ASCII
    python tools/font8x16_gen.py --c FILE   # also emit a C header

Nothing here ships to the device; it is a build-time tool for the PC side.
"""
import argparse
import ctypes
import ctypes.wintypes as wt
import io
import os
import sys

CELL_W = 8
CELL_H = 16
FIRST, LAST = 32, 126            # printable ASCII
FACE = "Consolas"                # fixed-pitch, present on every Windows box
PIXEL_HEIGHT = 14                # tmHeight = 15, ink occupies rows 1..14 of the cell
SHIFT_UP = 2                     # leave one blank row at the top of the cell

OUT_MODULE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "pcmon", "font8x16.py")

gdi32 = ctypes.WinDLL("gdi32", use_last_error=True)


class BITMAPINFOHEADER(ctypes.Structure):
    _fields_ = [("biSize", wt.DWORD), ("biWidth", ctypes.c_long), ("biHeight", ctypes.c_long),
                ("biPlanes", wt.WORD), ("biBitCount", wt.WORD), ("biCompression", wt.DWORD),
                ("biSizeImage", wt.DWORD), ("biXPelsPerMeter", ctypes.c_long),
                ("biYPelsPerMeter", ctypes.c_long), ("biClrUsed", wt.DWORD),
                ("biClrImportant", wt.DWORD)]


class BITMAPINFO(ctypes.Structure):
    _fields_ = [("bmiHeader", BITMAPINFOHEADER), ("bmiColors", wt.DWORD * 3)]


WHITENESS = 0x00FF0062


def render_cell(hdc, hbmp, code, y_offset):
    """Draw one character into the 8x16 mono bitmap; returns 16 row bytes."""
    bmi = BITMAPINFO()
    bmi.bmiHeader.biSize = ctypes.sizeof(BITMAPINFOHEADER)
    bmi.bmiHeader.biWidth = CELL_W
    bmi.bmiHeader.biHeight = CELL_H
    bmi.bmiHeader.biPlanes = 1
    bmi.bmiHeader.biBitCount = 1
    bits = (ctypes.c_ubyte * (4 * CELL_H))()      # 1bpp rows are DWORD aligned
    gdi32.PatBlt(hdc, 0, 0, CELL_W, CELL_H, WHITENESS)
    gdi32.TextOutW(hdc, 0, y_offset, chr(code), 1)
    gdi32.GetDIBits(hdc, hbmp, 0, CELL_H, bits, ctypes.byref(bmi), 0)
    rows = []
    for y in range(CELL_H - 1, -1, -1):           # DIB is bottom-up
        rows.append(bits[y * 4])                  # 0 bits are ink after WHITENESS
    return bytes(~row & 0xFF for row in rows)


def extract():
    hdc = gdi32.CreateCompatibleDC(None)
    hfont = gdi32.CreateFontW(-PIXEL_HEIGHT, CELL_W, 0, 0, 400, 0, 0, 0, 0, 0, 0, 0, 0, FACE)
    if not hfont:
        raise SystemExit("cannot create font %r" % FACE)
    old = gdi32.SelectObject(hdc, hfont)
    hbmp = gdi32.CreateBitmap(CELL_W, CELL_H, 1, 1, None)
    ob = gdi32.SelectObject(hdc, hbmp)
    gdi32.SetBkMode(hdc, 1)                       # TRANSPARENT
    gdi32.SetTextColor(hdc, 0x000000)
    glyphs = []
    try:
        for code in range(FIRST, LAST + 1):
            glyphs.append(render_cell(hdc, hbmp, code, -SHIFT_UP))
    finally:
        gdi32.SelectObject(hdc, ob)
        gdi32.DeleteObject(hbmp)
        gdi32.SelectObject(hdc, old)
        gdi32.DeleteObject(hfont)
        gdi32.DeleteDC(hdc)
    return glyphs


def art(rows):
    return "".join("#" if (r >> (7 - i)) & 1 else "." for i in range(8) for r in [rows[0]])


def show(glyphs, per_line=16):
    for start in range(0, len(glyphs), per_line):
        chunk = glyphs[start:start + per_line]
        labels = "".join("%-8s" % chr(FIRST + start + i) if i < len(chunk) else ""
                         for i in range(len(chunk)))
        print(labels)
        for row in range(CELL_H):
            line = ""
            for g in chunk:
                byte = g[row]
                line += "".join("#" if (byte >> (7 - b)) & 1 else "." for b in range(8))
            print(line)
        print()


def emit_module(glyphs, path):
    lines = [
        '"""8x16 dot-matrix font for the ST7735 preview (printable ASCII 32..126).',
        "",
        "Generated by tools/font8x16_gen.py from %s at %dpx, one byte per row," % (FACE, PIXEL_HEIGHT),
        "most significant bit = leftmost pixel, 1 = ink. Do not edit by hand:",
        "re-run the generator so the preview and the firmware table stay identical.",
        "",
        'The same bytes go to the panel: `python tools/font8x16_gen.py --c font8x16.h`.',
        '"""',
        "",
        "CELL_W = %d" % CELL_W,
        "CELL_H = %d" % CELL_H,
        "FIRST = %d" % FIRST,
        "LAST = %d" % LAST,
        "FACE = %r" % FACE,
        "",
        "GLYPHS = (",
    ]
    for code, glyph in zip(range(FIRST, LAST + 1), glyphs):
        hexed = "".join("\\x%02x" % b for b in glyph)
        lines.append("    b\"%s\",  # %d %r" % (hexed, code, chr(code)))
    lines += [
        ")",
        "",
        "",
        "def glyph(ch):",
        '    """Row bytes for one character; anything unprintable becomes a space."""',
        "    code = ord(ch[0]) if ch else 32",
        "    if not (FIRST <= code <= LAST):",
        "        code = 32",
        "    return GLYPHS[code - FIRST]",
        "",
        "",
        "def text_width(text):",
        '    """Pixels a string occupies, before clipping."""',
        "    return len(text) * CELL_W",
        "",
    ]
    io.open(path, "w", encoding="ascii", newline="\n").write("\n".join(lines) + "\n")


def emit_c(glyphs, path):
    out = ["/* 8x16 font, printable ASCII 32..126, generated by tools/font8x16_gen.py */",
           "#pragma once", "#include <stdint.h>",
           "#define FONT8X16_W 8", "#define FONT8X16_H 16", "#define FONT8X16_FIRST 32",
           "static const uint8_t font8x16[%d][%d] = {" % (len(glyphs), CELL_H)]
    for code, glyph in zip(range(FIRST, LAST + 1), glyphs):
        out.append("    {" + ", ".join("0x%02x" % b for b in glyph) + "},  /* %r */" % chr(code))
    out += ["};", ""]
    io.open(path, "w", encoding="ascii", newline="\n").write("\n".join(out) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description="extract the 8x16 dot-matrix font")
    ap.add_argument("--art", action="store_true", help="print every glyph as ASCII art")
    ap.add_argument("--c", default=None, metavar="FILE", help="also write a C header")
    ap.add_argument("--out", default=OUT_MODULE, help="python module to rewrite")
    args = ap.parse_args(argv)

    glyphs = extract()
    if len(glyphs) != LAST - FIRST + 1:
        raise SystemExit("expected %d glyphs, got %d" % (LAST - FIRST + 1, len(glyphs)))
    for code, glyph in zip(range(FIRST, LAST + 1), glyphs):
        if len(glyph) != CELL_H:
            raise SystemExit("glyph %r has %d rows" % (chr(code), len(glyph)))
    if args.art:
        show(glyphs)
    emit_module(glyphs, args.out)
    print("wrote %s (%d glyphs)" % (args.out, len(glyphs)))
    if args.c:
        emit_c(glyphs, args.c)
        print("wrote %s" % args.c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
